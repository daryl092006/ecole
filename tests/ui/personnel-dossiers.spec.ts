import { expect, test } from '@playwright/test';
import { authenticateFixture, snapshot as baseSnapshot } from './persistent-fixture';
import { teacherFixture } from './teacher-management-fixture';
import { securityContext, securityIds } from './security-fixture';
import { expectWorkspaceFits } from './helpers';

for (const width of [390, 1440]) test(`Personnel : création, historique et enseignant sans matricule à ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 950 });
  await authenticateFixture(page);
  const fixture = teacherFixture(securityContext(), true);
  let campusReads = 0;
  await page.route('**/api/campus', route => {
    campusReads++;
    return route.fulfill({ json: { ...fixture.snapshot, tables: { ...baseSnapshot.tables, ...fixture.snapshot.tables, people: [...baseSnapshot.tables.people, ...fixture.snapshot.tables.people] }, academicContext: { currentYearId: securityIds.year, currentYearConfigured: true, selectedYearId: securityIds.year, selection: 'current', years: fixture.snapshot.tables.academic_years } } });
  });
  await page.route('**/api/staff**', async route => {
    const request = route.request();
    const method = request.method();
    const input = new Request(request.url(), { method, headers: request.headers(), ...(method !== 'GET' ? { body: request.postData()! } : {}) });
    const response = method === 'GET' ? await fixture.staffApi.GET(input) : method === 'POST' ? await fixture.staffApi.POST(input) : await fixture.staffDetailApi.PATCH(input, { params: Promise.resolve({ personId: new URL(request.url()).pathname.split('/').at(-1)! }) });
    return route.fulfill({ status: response.status, json: await response.json() });
  });
  await page.goto('/personnel');
  await page.getByRole('button', { name: 'Nouveau membre du personnel', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('Matricule enseignant (facultatif)')).toHaveCount(0);
  await dialog.getByLabel('Prénom', { exact: true }).fill('Marie');
  await dialog.getByLabel('Nom', { exact: true }).fill('Comptable');
  await dialog.getByLabel('Fonction', { exact: true }).fill('Comptable');
  await dialog.getByLabel('Date de prise de fonction').fill('2026-10-01');
  await dialog.getByRole('button', { name: 'Vérifier les informations', exact: true }).click();
  await expect(dialog.locator('.review-values')).toContainText('2026-10-01');
  expect(fixture.transactions).toHaveLength(0);
  await dialog.getByRole('button', { name: 'Confirmer la création', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const member = page.getByRole('row').filter({ hasText: 'Marie Comptable' });
  await expect(member).toContainText('Personnel administratif');
  await member.getByRole('button', { name: 'Ouvrir', exact: true }).click();
  await dialog.getByRole('button', { name: 'Modifier le dossier', exact: true }).click();
  await dialog.getByLabel('Fonction', { exact: true }).fill('Secrétaire');
  await dialog.getByLabel('Motif', { exact: true }).fill('Changement de fonction validé');
  await dialog.getByRole('button', { name: 'Vérifier les informations', exact: true }).click();
  await expect(dialog.locator('.review-values')).toContainText('Avant : Comptable');
  await expect(dialog.locator('.action-consequence')).toContainText('clôturée');
  await dialog.getByRole('button', { name: 'Confirmer les modifications', exact: true }).click();
  await expect(member).toContainText('Secrétaire');
  await page.reload();
  await member.getByRole('button', { name: 'Ouvrir', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Historique des fonctions (2)' })).toBeVisible();
  await expect(dialog.getByRole('heading', { name: 'Comptable', exact: true })).toBeVisible();
  await expect(dialog.getByRole('heading', { name: 'Secrétaire', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Nouvel enseignant', exact: true }).click();
  await dialog.getByLabel('Prénom', { exact: true }).fill('Paul');
  await dialog.getByLabel('Nom', { exact: true }).fill('Professeur');
  await dialog.getByLabel('Spécialité enseignante').fill('Gestion');
  await dialog.getByRole('button', { name: 'Vérifier les informations', exact: true }).click();
  await expect(dialog.locator('.action-consequence')).toContainText('Aucun compte de connexion ni affectation');
  await dialog.getByRole('button', { name: 'Confirmer la création', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('combobox', { name: 'Profil', exact: true }).selectOption('teacher');
  await expect(page.getByRole('row').filter({ hasText: 'Paul Professeur' })).toBeVisible();
  await expect(member).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('row').filter({ hasText: 'Paul Professeur' })).toContainText('Enseignant');
  await expect(page.locator('#main-content')).not.toContainText('INT-');
  expect(fixture.transactions).toHaveLength(3);
  expect(campusReads).toBeGreaterThanOrEqual(4);
  await expectWorkspaceFits(page);
  await page.screenshot({ path: `tmp/screenshots/personnel-review/${width}/personnel-enseignants.png`, fullPage: true });
});
